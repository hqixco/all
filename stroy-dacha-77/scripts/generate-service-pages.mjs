function replaceCaseImages(html, images) {
  let index = 0;

  return html.replace(
    /data-case-slider-images='\[[\s\S]*?\]'\s+style="--case-card-image: url\('[^']+'\);"/g,
    (match) => {
      const image = images[index];
      index += 1;
      if (!image) return match;

      const imagePath = `/assets/${image}`;
      const title = `Фото работ по кровле ${index}`;

      return `data-case-slider-images='[
                {"image":"${imagePath}","title":"${title}"}
              ]'
              style="--case-card-image: url('${imagePath}');"`;
    }
  );
}

